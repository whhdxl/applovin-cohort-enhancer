import { readFileSync, writeFileSync } from 'node:fs';
const files = ['core.js', 'mui-main.js'];
const bundle = '// Generated by npm run build. Edit core.js or mui-main.js.\n' + files.map(file => readFileSync(`extension/${file}`, 'utf8')).join('\n');
writeFileSync('extension/mui-runtime.js', bundle);
console.log('Built MAIN-world MUI runtime.');
